male = 0
female = 0

# Age distribution
less_than_25 = 0
age_25_to_35 = 0
above_35 = 0

# Developer count
developers = 0

# Employee language lists
java_employees = []
python_employees = []
both_java_python = []

for emp in employees:
    gender = emp['personal_information']['gender']
    age = emp['personal_information']['age']
    role = emp['department_information']['role']
    languages = emp['skills_information']['languages']
    name = emp['name']

    if gender == 'M':
        male += 1
    elif gender == 'F':
        female += 1

    if age < 25:
        less_than_25 += 1
    elif age <= 35:
        age_25_to_35 += 1
    else:
        above_35 += 1

    if role == 'Developer':
        developers += 1

    if 'Java' in languages:
        java_employees.append(name)

    if 'Python' in languages:
        python_employees.append(name)

    if 'Java' in languages and 'Python' in languages:
        both_java_python.append(name)

